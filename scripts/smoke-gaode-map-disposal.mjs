import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { pathToFileURL } from "node:url";
import { build } from "esbuild";
const dir = ".scratch/runtime-smoke";
mkdirSync(dir, { recursive: true });
const entry = resolve(`${dir}/gaode-map-disposal-entry.ts`);
const bundle = resolve(`${dir}/gaode-map-disposal-bundle.mjs`);
const source = readFileSync("src/components/GaodeCampusBoundaryEditor.tsx", "utf8");
if (/ref=\{hostRef\}\s+className=\{/.test(source) || !source.includes('ref={hostRef} className="gaode-boundary-map"')) throw new Error("React must not rewrite the AMap host class after AMap adds runtime layout classes");
if (!source.includes("onDeselect")) throw new Error("Gaode geometry editing needs an explicit exit path");
if (source.includes("[geometryType, maxPoints, onChangePoints")) throw new Error("Inline callback identity must not force a full map overlay rebuild");
writeFileSync(entry, `
import { disposeGaodeMap, editableMidpointEdgeIndexes, loadGaodeMapView, saveGaodeMapView } from "../../src/components/GaodeCampusBoundaryEditor";
const calls: string[] = [];
const stored = new Map<string,string>();
const storage = { getItem:(key:string)=>stored.get(key)??null, setItem:(key:string,value:string)=>void stored.set(key,value) };
const fallback = { center:{lng:121,lat:31}, zoom:17, pitch:42, rotation:0 };
saveGaodeMapView("campus", { center:{lng:122,lat:32}, zoom:19, pitch:20, rotation:15 }, storage);
const remembered = loadGaodeMapView("campus", fallback, storage);
if (remembered.center.lng !== 122 || remembered.zoom !== 19 || remembered.pitch !== 20 || remembered.rotation !== 15) throw new Error("Gaode camera view must survive remounts");
const midpointEdges = editableMidpointEdgeIndexes(50, 25, "polygon");
if (midpointEdges.join(",") !== "24,25") throw new Error("Only the two edges adjacent to the selected vertex should expose insertion handles");
if (editableMidpointEdgeIndexes(50, 25, "polygon", 50).length !== 0) throw new Error("Insertion handles must be hidden at the point limit");
disposeGaodeMap({ remove() { calls.push("remove"); }, destroy() { calls.push("destroy"); } }, [{}]);
if (calls.join(",") !== "remove,destroy") throw new Error("Gaode overlays must be removed before map destruction");
disposeGaodeMap({ remove() { throw new Error("already disposed"); }, destroy() { throw new Error("destroy failed"); } }, [{}]);
console.log("Gaode map disposal smoke test passed.");
`);
await build({ entryPoints:[entry], outfile:bundle, bundle:true, platform:"node", format:"esm", target:"node20", logLevel:"silent" });
await import(`${pathToFileURL(bundle).href}?t=${Date.now()}`);
